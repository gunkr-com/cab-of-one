"""Module selection rules, ``rules/modules.toml`` (DESIGN §10-4-4).

Each ``[[module]]`` has a fixed id and exactly one data-only condition:

- ``always = true`` (only the ``core`` module, which must have it);
- ``when_any = ["systems.intune", ...]``: a listed boolean field is true or a listed list
  field is non-empty;
- ``when_eq = { "session.permission_mode" = "manual" }``: every listed field equals its
  value (enum or boolean fields only; the value type and choice are checked on load).

A module may contribute ``files`` (``src`` under the source root, ``dst`` in the project,
optional ``substitute`` for ``string.Template`` prose), runtime ``adapters``, extra
``critical_patterns``, ``notices`` (plain text for the setup plan) and ``features`` (named
profile-value generators the renderer knows). Nothing is evaluated. The same profile and the
same rules always select the same modules, in id order.

The core module is the floor: it must exist, be ``always``, and carry every mapping in
``CORE_REQUIRED_FILES``. A rules file that weakens it is refused.
"""

from __future__ import annotations

import os
import re
import stat
import tomllib
from dataclasses import dataclass
from typing import Any

from ..runtime.adapters import ADAPTER_NAMES
from . import profile as profile_mod

__all__ = [
    "CORE_ID",
    "CORE_REQUIRED_FILES",
    "FEATURES",
    "FileSpec",
    "Module",
    "Rules",
    "RulesError",
    "load_rules",
    "select_modules",
]

SCHEMA_VERSION = 1
MAX_RULES_BYTES = 64 * 1024
MAX_MODULES = 64
CORE_ID = "core"

#: (src, dst) pairs the core module must map. The floor files (hook entries, pinned runtime,
#: agents, skills, CLAUDE.md block) come from these; render checks the result again.
CORE_REQUIRED_FILES = (
    ("templates/core/hooks/", ".claude/hooks/cab/"),
    ("src/cab_of_one/__init__.py", ".claude/hooks/cab/cab_of_one/__init__.py"),
    ("src/cab_of_one/runtime/", ".claude/hooks/cab/cab_of_one/runtime/"),
    ("templates/core/agents/", ".claude/agents/"),
    ("templates/core/skills/", ".claude/skills/"),
    ("templates/core/CLAUDE.md", "CLAUDE.md"),
)

#: Profile-value generators in render.py that a module may switch on.
FEATURES = frozenset(
    {"disable_bypass_mode", "mcp_write_servers", "read_deny_paths", "simtenant_trust"}
)

#: Project files a module may write: anything below these folders, or exactly these files.
DST_FOLDERS = (".claude/", "docs/", "simtenant/")
DST_FILES = frozenset(
    {"CLAUDE.md", "PROGRESS.md", "HANDOFF.md", "changes/README.md", "audit/README.md"}
)
#: Generated by render.py itself; no module may provide them.
RESERVED_DST = frozenset(
    {
        ".claude/settings.json",
        ".claude/settings.local.json",
        "policy/policy.toml",
        "policy/standard-changes.toml",
    }
)

_ID = re.compile(r"[a-z][a-z0-9-]{0,31}")
_PART = re.compile(r"[A-Za-z0-9_.-]{1,64}")
_CONTROL = re.compile(r"[\x00-\x1f\x7f]")
_MODULE_KEYS = frozenset(
    {
        "id",
        "description",
        "always",
        "when_any",
        "when_eq",
        "files",
        "adapters",
        "critical_patterns",
        "notices",
        "features",
    }
)
_OPEN_READ = os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC | os.O_NONBLOCK


class RulesError(ValueError):
    """The rules file is refused. ``where`` is a module id or a key name, never a value."""

    def __init__(self, code: str, where: str | None = None) -> None:
        super().__init__(code if where is None else f"{code}: {where}")
        self.code = code
        self.where = where


@dataclass(frozen=True)
class FileSpec:
    src: str
    dst: str
    substitute: bool

    @property
    def is_dir(self) -> bool:
        return self.src.endswith("/")


@dataclass(frozen=True)
class Module:
    id: str
    always: bool
    when_any: tuple[str, ...]
    when_eq: tuple[tuple[str, str | bool], ...]
    files: tuple[FileSpec, ...]
    adapters: tuple[str, ...]
    critical_patterns: tuple[str, ...]
    notices: tuple[str, ...]
    features: tuple[str, ...]

    def applies(self, profile: profile_mod.Profile) -> bool:
        if self.always:
            return True
        if self.when_any:
            return any(_truthy(profile[key]) for key in self.when_any)
        return all(_equal(profile[key], value) for key, value in self.when_eq)


@dataclass(frozen=True)
class Rules:
    modules: tuple[Module, ...]  # sorted by id

    def ids(self) -> tuple[str, ...]:
        return tuple(m.id for m in self.modules)


def _truthy(value: Any) -> bool:
    if type(value) is bool:
        return value
    if isinstance(value, tuple):
        return bool(value)
    raise RulesError("condition_type")


def _equal(actual: Any, expected: Any) -> bool:
    return type(actual) is type(expected) and actual == expected


# --------------------------------------------------------------------------- loading


def load_rules(source: str | os.PathLike[str] | bytes | bytearray) -> Rules:
    """Load and validate ``rules/modules.toml`` from a path or bytes."""
    if isinstance(source, bytes | bytearray):
        data = bytes(source)
    elif isinstance(source, str | os.PathLike):
        data = _read_file(os.fspath(source))
    else:
        raise RulesError("source_type")
    if len(data) > MAX_RULES_BYTES:
        raise RulesError("too_large")
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        raise RulesError("encoding") from None
    if text.startswith("﻿"):
        raise RulesError("bom")
    try:
        doc = tomllib.loads(text)
    except (tomllib.TOMLDecodeError, RecursionError, ValueError):
        raise RulesError("syntax") from None
    return _build(doc)


def select_modules(profile: profile_mod.Profile, rules: Rules) -> list[Module]:
    """Modules that apply to ``profile``, in id order. The core module is always first-class."""
    if not isinstance(profile, profile_mod.Profile):
        raise RulesError("not_profile")
    if not isinstance(rules, Rules):
        raise RulesError("not_rules")
    chosen = [m for m in rules.modules if m.applies(profile)]
    if CORE_ID not in {m.id for m in chosen}:
        raise RulesError("core_missing")
    return chosen


def _read_file(path: str) -> bytes:
    if not path or "\x00" in path:
        raise RulesError("source_type")
    try:
        fd = os.open(path, _OPEN_READ)
    except FileNotFoundError:
        raise RulesError("rules_missing") from None
    except OSError:
        raise RulesError("rules_unreadable") from None
    try:
        st = os.fstat(fd)
        if not stat.S_ISREG(st.st_mode) or st.st_size > MAX_RULES_BYTES:
            raise RulesError("rules_unreadable")
        data = os.read(fd, MAX_RULES_BYTES + 1)
    finally:
        os.close(fd)
    return data


def _build(doc: dict[str, Any]) -> Rules:
    if set(doc) - {"schema", "module"}:
        raise RulesError("unknown_key", "<top level>")
    if type(doc.get("schema")) is not int or doc["schema"] != SCHEMA_VERSION:
        raise RulesError("schema_version")
    raw = doc.get("module")
    if type(raw) is not list or not raw or len(raw) > MAX_MODULES:
        raise RulesError("modules")
    modules: dict[str, Module] = {}
    for entry in raw:
        module = _module(entry)
        if module.id in modules:
            raise RulesError("duplicate_id", module.id)
        modules[module.id] = module
    _check_core(modules.get(CORE_ID))
    seen: dict[str, str] = {}
    for module in modules.values():
        for spec in module.files:
            if spec.dst in seen:
                raise RulesError("duplicate_dst", module.id)
            seen[spec.dst] = module.id
    return Rules(tuple(modules[key] for key in sorted(modules)))


def _check_core(core: Module | None) -> None:
    if core is None:
        raise RulesError("core_missing")
    if not core.always:
        raise RulesError("core_conditional", CORE_ID)
    present = {(spec.src, spec.dst) for spec in core.files}
    for pair in CORE_REQUIRED_FILES:
        if pair not in present:
            raise RulesError("core_incomplete", CORE_ID)


def _module(entry: Any) -> Module:
    if not isinstance(entry, dict):
        raise RulesError("module")
    mid = entry.get("id")
    if type(mid) is not str or not _ID.fullmatch(mid):
        raise RulesError("module_id")
    if set(entry) - _MODULE_KEYS:
        raise RulesError("unknown_key", mid)
    if "description" in entry:
        _text(entry["description"], mid, 200)

    forms = [key for key in ("always", "when_any", "when_eq") if key in entry]
    if len(forms) != 1:
        raise RulesError("condition_count", mid)
    always = False
    when_any: tuple[str, ...] = ()
    when_eq: tuple[tuple[str, str | bool], ...] = ()
    if forms[0] == "always":
        if entry["always"] is not True:
            raise RulesError("condition_always", mid)
        if mid != CORE_ID:
            raise RulesError("always_reserved", mid)
        always = True
    elif forms[0] == "when_any":
        when_any = _when_any(entry["when_any"], mid)
    else:
        when_eq = _when_eq(entry["when_eq"], mid)

    files = tuple(_file(item, mid) for item in _list(entry.get("files", []), mid, 32))
    adapters = _str_tuple(entry.get("adapters", []), mid, 8, 32)
    if not set(adapters) <= set(ADAPTER_NAMES):
        raise RulesError("adapter_unknown", mid)
    patterns = _str_tuple(entry.get("critical_patterns", []), mid, 64, 256)
    notices = _str_tuple(entry.get("notices", []), mid, 8, 400)
    features = _str_tuple(entry.get("features", []), mid, 8, 64)
    if not set(features) <= FEATURES:
        raise RulesError("feature_unknown", mid)
    return Module(mid, always, when_any, when_eq, files, adapters, patterns, notices, features)


def _when_any(value: Any, mid: str) -> tuple[str, ...]:
    keys = _str_tuple(value, mid, 16, 64)
    if not keys:
        raise RulesError("condition_empty", mid)
    for key in keys:
        spec = profile_mod.FIELDS.get(key)
        if spec is None or spec.kind not in ("bool", "list"):
            raise RulesError("condition_field", mid)
    return keys


def _when_eq(value: Any, mid: str) -> tuple[tuple[str, str | bool], ...]:
    if not isinstance(value, dict) or not value or len(value) > 8:
        raise RulesError("condition_empty", mid)
    out = []
    for key in sorted(value):
        expected = value[key]
        spec = profile_mod.FIELDS.get(key)
        if spec is None or spec.kind not in ("bool", "enum"):
            raise RulesError("condition_field", mid)
        if spec.kind == "bool" and type(expected) is not bool:
            raise RulesError("condition_value", mid)
        if spec.kind == "enum" and (type(expected) is not str or expected not in spec.choices):
            raise RulesError("condition_value", mid)
        out.append((key, expected))
    return tuple(out)


def _file(value: Any, mid: str) -> FileSpec:
    if not isinstance(value, dict) or set(value) - {"src", "dst", "substitute"}:
        raise RulesError("file_spec", mid)
    src, dst = value.get("src"), value.get("dst")
    substitute = value.get("substitute", False)
    if type(substitute) is not bool:
        raise RulesError("file_spec", mid)
    if not _rel(src, allow_dir=True) or not _rel(dst, allow_dir=True):
        raise RulesError("file_path", mid)
    if src.endswith("/") != dst.endswith("/"):
        raise RulesError("file_path", mid)
    if src.endswith("/") and substitute:
        raise RulesError("file_spec", mid)  # prose substitution is per named file
    if dst.endswith("/"):
        if not any(dst.startswith(folder) for folder in DST_FOLDERS):
            raise RulesError("file_dst", mid)
    elif dst in RESERVED_DST or not (
        dst in DST_FILES or any(dst.startswith(folder) for folder in DST_FOLDERS)
    ):
        raise RulesError("file_dst", mid)
    return FileSpec(src, dst, substitute)


def _rel(value: Any, *, allow_dir: bool) -> bool:
    if type(value) is not str or not value or len(value) > 256 or value.startswith("/"):
        return False
    body = value[:-1] if allow_dir and value.endswith("/") else value
    parts = body.split("/")
    return all(_PART.fullmatch(p) and set(p) != {"."} for p in parts)


def _list(value: Any, mid: str, max_items: int) -> list[Any]:
    if type(value) is not list or len(value) > max_items:
        raise RulesError("list", mid)
    return value


def _text(value: Any, mid: str, max_len: int) -> str:
    if type(value) is not str or not value or len(value) > max_len or _CONTROL.search(value):
        raise RulesError("text", mid)
    return value


def _str_tuple(value: Any, mid: str, max_items: int, max_len: int) -> tuple[str, ...]:
    items = tuple(_text(v, mid, max_len) for v in _list(value, mid, max_items))
    if len(set(items)) != len(items):
        raise RulesError("duplicate_entry", mid)
    return items
